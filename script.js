function layout(ex) {
  if (!ex.nat) return;
  const W = innerWidth, H = innerHeight, p = ex.page, mobile = isMobile();
  const nr = ex.note.getBoundingClientRect();
  const top = mobile ? 64 : 80, bottom = mobile ? 0 : 70, side = Math.max(24, W * .04);
  const gap = mobile ? 14 : 44;
  let rx, ry = top, rw, rh;

  if (mobile) {
    rx = 12; rw = W - 24;
    if (!ex.note.classList.contains("open")) ex.cacheBottom = nr.top - gap;
    rh = (ex.cacheBottom || H * .5) - ry;
  } else if (p.textPosition === "left") {
    rx = nr.right + gap; rw = W - rx - side; rh = H - top - bottom;
  } else if (p.textPosition === "right") {
    rx = side; rw = nr.left - gap - rx; rh = H - top - bottom;
  } else {
    rx = side; rw = W - 2 * side; rh = H - top - bottom;
  }
  rw = Math.max(80, rw);
  rh = Math.max(80, rh);

  const s = Math.min(rw / ex.nat.w, rh / ex.nat.h);
  const fw = ex.nat.w * s, fh = ex.nat.h * s;
  const fx = rx + (rw - fw) / 2, fy = ry + (rh - fh) / 2;

  ex.frame.style.left = fx + "px";
  ex.frame.style.top = fy + "px";
  ex.frame.style.width = fw + "px";
  ex.frame.style.height = fh + "px";
}

