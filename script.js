function render(text, cls) {
  const c = cls ? ` class="${cls}"` : "";
  return text.trim().split(/\n\s*\n/).map(block => {
    const t = block.trim();
    if (/^### /.test(t)) return `<h3 class="callout${cls ? " " + cls : ""}">${inline(t.slice(4))}</h3>`;
    if (/^# /.test(t)) return `<h2 class="big${cls ? " " + cls : ""}">${inline(t.slice(2))}</h2>`;
    if (/^> /.test(t)) return `<blockquote${c}>${inline(t.replace(/^>\s?/gm, ""))}</blockquote>`;
    return `<p${c}>${inline(t).replace(/\n/g, "<br>")}</p>`;
  }).join("");
}

